function read(file) {
  return readFileSync(join(root, file), 'utf8');
}

function assertIncludes(source, needle, message = `Missing ${needle}`) {
  assert.ok(source.includes(needle), message);
}

function assertInlineScriptsParse(file) {
  const html = read(file);
  const scripts = [...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi)].map((match) => match[1].trim()).filter(Boolean);
  assert.ok(scripts.length > 0, `${file} should include inline runtime scripts`);
  scripts.forEach((script, index) => {
    assert.doesNotThrow(() => new Script(script), `${file} inline script ${index + 1} should parse`);
  });
}

