  function criterionKey(criterion) {
    return ['type', 'command', 'direction', 'steps', 'turn', 'times', 'min', 'state']
      .map(key => `${key}:${criterion[key] ?? ''}`)
      .join('|');
  }

  function appendExerciseSentence(text, sentence) {
    if (!sentence || text.includes(sentence)) return text;
    return `${text} ${sentence}`;
  }

