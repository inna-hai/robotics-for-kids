  function summarizeHigherLevelChange(criterion) {
    if (criterion.type === 'chatDeliver' || criterion.type === 'command') return 'התרגיל שונה כך שהפתרון צריך לשמור על פקודת הפעלה נכונה שמריצה רצף מלא.';
    if (criterion.type === 'teleport') return 'התרגיל שונה כך שהפתרון צריך להתחיל מנקודת התחלה יציבה גם אחרי תיקון.';
    if (criterion.type === 'firstMove' || criterion.type === 'secondMove' || criterion.type === 'anyMove') return 'התרגיל שונה כך שהתלמיד צריך למצוא מספר צעדים מדויק לפי הרצה ותיקון.';
    if (criterion.type === 'moveCount') return 'התרגיל שונה כך שנדרש רצף תנועה מלא שבו לכל תנועה יש תפקיד במסלול.';
    if (criterion.type === 'moveBeforeTurn' || criterion.type === 'turnBeforeSecondMove' || criterion.type === 'turn') return 'התרגיל שונה כך שנדרש תכנון מדויק של סדר התנועה והפנייה.';
    if (criterion.type === 'reachedStation') return 'התרגיל שונה כך שנדרשת הגעה מדויקת ליעד לפי בדיקה בעולם.';
    if (criterion.type === 'place' || criterion.type === 'placeDirection' || criterion.type === 'packageNearStation' || criterion.type === 'placeCount') return 'התרגיל שונה כך שהסימון בעולם צריך להוכיח שהפעולה קרתה במקום הנכון.';
    if (criterion.type === 'repeat' || criterion.type === 'repeatTimes' || criterion.type === 'returnToStart') return 'התרגיל שונה כך שנדרש מחזור יציב שאפשר להריץ שוב, ולא רק רצף חד-פעמי.';
    if (criterion.type === 'condition' || criterion.type === 'conditionState' || criterion.type === 'elseBranch' || criterion.type === 'elseSay') return 'התרגיל שונה כך שנדרשת בדיקה של שני מצבים ותגובה ברורה לכל מצב.';
    if (criterion.type === 'repeatOrCondition') return 'התרגיל שונה כך שנדרש לבחור רעיון תכנותי מתקדם שמתאים למערכת.';
    if (criterion.type === 'say' || criterion.type === 'arrivalSay' || criterion.type === 'arrivalSayAfterMove') return 'התרגיל שונה כך שנדרשת הודעת הסבר שמוכיחה הבנה של תוצאת ההרצה.';
    if (criterion.type === 'staysOnStartRow') return 'התרגיל שונה כך שנדרשת בדיקה שהפתרון נשאר בתחום המסלול שתוכנן.';
    return 'התרגיל שונה כך שנדרשת בדיקה מדויקת יותר של הפתרון.';
  }

  function addExerciseCriterion(exercise, criterion) {
    exercise.criteria = exercise.criteria || [];
    const key = criterionKey(criterion);
    if (!exercise.criteria.some(existing => criterionKey(existing) === key)) {
      exercise.criteria.push(criterion);
    }
  }

  Object.entries(agentAcademyExerciseRefinements).forEach(([challengeId, lessonRefinements]) => {
    lessonRefinements.forEach((exerciseRefinements, lessonIndex) => {
      const academy = detailsByChallenge[challengeId]?.[lessonIndex]?.academy;
      if (!academy?.exercises || academy.skipRefinements) return;
      exerciseRefinements.forEach((refinement, exerciseIndex) => {
        const exercise = academy.exercises[exerciseIndex];
        if (!exercise) return;
        exercise.refinementSummary = summarizeHigherLevelChange(refinement.criterion);
        // Debug exercises keep their step-by-step debugging instructions without an extra sentence.
        if (!exercise.debugStart) exercise.mission = appendExerciseSentence(exercise.mission, makeHigherLevelPrompt(refinement.criterion) || refinement.prompt);
        exercise.check = appendExerciseSentence(exercise.check, `בנוסף, ${refinement.check}`);
        addExerciseCriterion(exercise, refinement.criterion);
      });
    });
  });

